package sg.edu.ntu.taskflowapi.service;

import java.time.LocalDateTime;
import java.util.List;

import org.springframework.stereotype.Service;

import sg.edu.ntu.taskflowapi.exceptions.TaskNotFoundException;
import sg.edu.ntu.taskflowapi.model.Task;
import sg.edu.ntu.taskflowapi.repository.TaskRepository;

/**
 * Holds the business logic of the TaskFlow API and talks to the repository.
 *
 * The repository is brought in with constructor injection - Spring creates the
 * repository bean and passes it in when it builds this service.
 */
@Service
public class TaskServiceImp implements TaskService {

    private final TaskRepository taskRepository;

    public TaskServiceImp(TaskRepository taskRepository) {
        this.taskRepository = taskRepository;
    }

    /**
     * Returns every task.
     *
     * @return a list of all tasks
     */
    @Override
    public List<Task> findAllTasks() {
        return taskRepository.findAll();
    }

    /**
     * Returns a single task.
     *
     * @param id the id of the task
     * @return the task
     * @throws TaskNotFoundException if no task has that id
     */
    @Override
    public Task findTaskById(Long id) {
        return taskRepository.findById(id)
                .orElseThrow(() -> new TaskNotFoundException(id));
    }

    /**
     * Creates a new task. The id is generated by the repository.
     *
     * @param task the task to create
     * @return the created task, including its generated id
     */
    @Override
    public Task createTask(Task task) {
        // A new task always starts out as not completed, whatever the client sent.
        task.setId(null);
        task.setCreatedDate(java.time.LocalDateTime.now());
        task.setCompleted(false);
        return taskRepository.save(task);
    }

    /**
     * Updates an existing task.
     *
     * @param id   the id of the task to update
     * @param task the new values for the task
     * @return the updated task
     * @throws TaskNotFoundException if no task has that id
     */
    @Override
    public Task updateTask(Long id, Task task) {
        Task existingTask = findTaskById(id);
        existingTask.setTitle(task.getTitle());
        existingTask.setDescription(task.getDescription());
        existingTask.setCompleted(task.isCompleted());
        if (task.isCompleted() ) {
            if (existingTask.getCompletedDate() == null) {
                existingTask.setCompletedDate(LocalDateTime.now());
            }
        } else {
            existingTask.setCompletedDate(null);
        }
        return taskRepository.save(existingTask);
    }

    /**
     * Deletes a task.
     *
     * @param id the id of the task to delete
     * @throws TaskNotFoundException if no task has that id
     */
    @Override
    public void deleteTask(Long id) {
        if (!taskRepository.deleteById(id)) {
            throw new TaskNotFoundException(id);
        }
    }

    /**
     * Marks a task as complete.
     *
     * @param id the id of the task to complete
     * @return the completed task
     * @throws TaskNotFoundException if no task has that id
     */
    @Override
    public Task markTaskAsComplete(Long id) {
        Task task = findTaskById(id);
        task.setCompleted(true);
        task.setCompletedDate(LocalDateTime.now());
        return taskRepository.save(task);
    }
}
